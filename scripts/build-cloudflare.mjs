import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const publicDir = path.join(rootDir, "public");
const publicBuildDir = path.join(publicDir, "build");
const distDir = path.join(rootDir, "dist");
const cloudflareDir = path.join(rootDir, "cloudflare");

function escapeHtml(value) {
    return String(value ?? "")
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");
}

function main() {
    const manifestPath = path.join(publicBuildDir, "manifest.json");
    if (!fs.existsSync(manifestPath)) {
        throw new Error(
            `Vite manifest not found at ${manifestPath}. Run "vite build" first.`,
        );
    }

    const manifestRaw = fs.readFileSync(manifestPath, "utf8");
    const manifest = JSON.parse(manifestRaw);
    const versionHash = crypto
        .createHash("sha256")
        .update(manifestRaw)
        .digest("hex")
        .slice(0, 16);

    const appEntry = manifest["resources/js/app.jsx"] || {};
    const cssEntry = manifest["resources/css/app.css"] || {};

    const jsFile = appEntry.file || "assets/app.js";
    const cssFiles = Array.from(
        new Set([...(cssEntry.file ? [cssEntry.file] : []), ...(appEntry.css || [])]),
    );

    // 1. Write cloudflare/build-meta.js for Cloudflare Workers & Pages Functions
    fs.mkdirSync(cloudflareDir, { recursive: true });
    const buildMetaContent = `// Auto-generated by scripts/build-cloudflare.mjs — do not edit manually.
export const BUILD_META = ${JSON.stringify(
        {
            version: versionHash,
            cssFiles,
            jsFile,
        },
        null,
        4,
    )};
`;
    fs.writeFileSync(
        path.join(cloudflareDir, "build-meta.js"),
        buildMetaContent,
        "utf8",
    );

    // 2. Prepare dist/ directory for Cloudflare Pages & Workers Static Assets
    fs.rmSync(distDir, { recursive: true, force: true });
    fs.mkdirSync(distDir, { recursive: true });

    // Copy public/build -> dist/build
    fs.cpSync(publicBuildDir, path.join(distDir, "build"), { recursive: true });

    // Copy public static root files
    for (const file of ["favicon.png", "favicon.ico", "robots.txt"]) {
        const src = path.join(publicDir, file);
        if (fs.existsSync(src)) {
            fs.copyFileSync(src, path.join(distDir, file));
        }
    }

    // 3. Generate dist/index.html (SPA fallback shell with default Inertia page payload)
    const defaultPage = {
        component: "Website/Home",
        props: {
            errors: {},
            auth: {
                user: null,
                rememberedProfile: null,
                googleEnabled: false,
            },
            flash: {
                success: null,
                error: null,
            },
        },
        url: "/",
        version: versionHash,
        staticFallback: true,
    };

    const cssLinks = cssFiles
        .map((css) => `    <link rel="stylesheet" href="/build/${css}">`)
        .join("\n");

    const indexHtml = `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title inertia>RAVU — Move further together | Mobility Ecosystem Tanzania</title>
    <meta inertia name="description" content="RAVU is a membership-based mobility ecosystem connecting people, businesses, services and technology to make mobility work better.">
    <meta name="theme-color" content="#020617">
    <link rel="icon" type="image/png" href="/favicon.png">
    <link rel="preconnect" href="https://fonts.bunny.net">
    <link href="https://fonts.bunny.net/css?family=inter:400,500,600,700,800,900&display=swap" rel="stylesheet">
${cssLinks}
    <script type="module" src="/build/${jsFile}"></script>
</head>
<body class="antialiased">
    <div id="app" data-page="${escapeHtml(JSON.stringify(defaultPage))}"></div>
</body>
</html>
`;
    fs.writeFileSync(path.join(distDir, "index.html"), indexHtml, "utf8");

    // 4. Generate dist/_redirects for Cloudflare Pages static SPA fallback
    const redirectsContent = `# Cloudflare Pages SPA fallback
/admin /super-admin 302
/partner-portal /partner-dashboard 302
/* /index.html 200
`;
    fs.writeFileSync(path.join(distDir, "_redirects"), redirectsContent, "utf8");

    // 5. Generate dist/_headers for Cloudflare Pages caching & security headers
    const headersContent = `/build/assets/*
  Cache-Control: public, max-age=31536000, immutable

/favicon.png
  Cache-Control: public, max-age=86400

/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: SAMEORIGIN
  Referrer-Policy: strict-origin-when-cross-origin
`;
    fs.writeFileSync(path.join(distDir, "_headers"), headersContent, "utf8");

    // 6. Generate dist/_routes.json so Cloudflare Pages serves static assets directly from CDN
    const routesJson = {
        version: 1,
        include: ["/*"],
        exclude: [
            "/build/*",
            "/favicon.png",
            "/favicon.ico",
            "/robots.txt",
            "/_headers",
            "/_redirects",
        ],
    };
    fs.writeFileSync(
        path.join(distDir, "_routes.json"),
        JSON.stringify(routesJson, null, 4) + "\n",
        "utf8",
    );

    // Remove stale public/hot if present so production build assets are used
    const hotFile = path.join(publicDir, "hot");
    if (fs.existsSync(hotFile)) {
        fs.rmSync(hotFile, { force: true });
    }

    console.log(
        `[Cloudflare Build] Ready! Output directory: dist/ (version: ${versionHash})`,
    );
}

main();
